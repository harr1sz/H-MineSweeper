const catalogs: Record<SupportedLocale, Record<MessageId, MessageTemplate>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export interface MessageDescriptor {
  readonly id: MessageId;
  readonly values?: MessageValues;
}

function normalizeLocale(value: string | null | undefined): SupportedLocale | null {
  if (!value) return null;
  const normalized = value.toLowerCase();
  if (
    normalized === "zh" ||
    normalized.startsWith("zh-cn") ||
    normalized.startsWith("zh-hans") ||
    normalized.startsWith("zh-sg")
  ) {
    return "zh-CN";
  }
  if (normalized === "en" || normalized.startsWith("en-")) {
    return "en-US";
  }
  return null;
}

function safeReadStoredLocale(): SupportedLocale | null {
  if (typeof window === "undefined") return null;
  try {
    return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
  } catch {
    return null;
  }
}

export function resolveInitialLocale(
  stored: string | null = safeReadStoredLocale(),
  languages: readonly string[] =
    typeof navigator === "undefined" ? [] : navigator.languages,
): SupportedLocale {
  const storedLocale = normalizeLocale(stored);
  if (storedLocale) return storedLocale;
  for (const language of languages) {
    const locale = normalizeLocale(language);
    if (locale) return locale;
  }
  return "zh-CN";
}

export function translate(
  locale: SupportedLocale,
  id: MessageId,
  values: MessageValues = {},
): string {
  const template = catalogs[locale][id];
  return typeof template === "function" ? template(values) : template;
}

interface LocaleContextValue {
  readonly locale: SupportedLocale;
  readonly t: (id: MessageId, values?: MessageValues) => string;
  readonly formatNumber: (value: number) => string;
  readonly formatDateTime: (value: Date | number | string) => string;
  readonly setLocale: (locale: SupportedLocale) => void;
  readonly toggleLocale: () => void;
  readonly persistenceWarning: string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

const initialLocale = resolveInitialLocale();

export function LocaleProvider({ children }: { readonly children: ReactNode }) {
  const [locale, setLocaleState] = useState<SupportedLocale>(initialLocale);
  const [persistenceWarning, setPersistenceWarning] = useState("");

  const t = useCallback(
    (id: MessageId, values: MessageValues = {}) =>
      translate(locale, id, values),
    [locale],
  );

  const setLocale = useCallback((nextLocale: SupportedLocale) => {
    setLocaleState(nextLocale);
    setPersistenceWarning("");
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
    } catch {
      setPersistenceWarning(
        translate(nextLocale, "language.persistenceFailed"),
      );
    }
  }, []);

  const toggleLocale = useCallback(() => {
    setLocale(locale === "zh-CN" ? "en-US" : "zh-CN");
  }, [locale, setLocale]);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = locale;
    document.title = translate(locale, "meta.title");
    const setMetaContent = (selector: string, messageId: MessageId) => {
      document
        .querySelector(selector)
        ?.setAttribute("content", translate(locale, messageId));
    };
    setMetaContent('meta[name="description"]', "meta.description");
    setMetaContent('meta[property="og:title"]', "meta.socialTitle");
    setMetaContent('meta[property="og:description"]', "meta.socialDescription");
    setMetaContent('meta[name="twitter:title"]', "meta.socialTitle");
    setMetaContent('meta[name="twitter:description"]', "meta.socialDescription");
  }, [locale]);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const synchronizeLocale = (event: StorageEvent) => {
      if (event.key !== LOCALE_STORAGE_KEY) return;
      const next = normalizeLocale(event.newValue);
      if (next) setLocaleState(next);
    };
    window.addEventListener("storage", synchronizeLocale);
    return () => window.removeEventListener("storage", synchronizeLocale);
  }, []);

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      t,
      formatNumber: (input) => new Intl.NumberFormat(locale).format(input),
      formatDateTime: (input) =>
        new Intl.DateTimeFormat(locale, {
          dateStyle: "medium",
          timeStyle: "short",
        }).format(new Date(input)),
      setLocale,
      toggleLocale,
      persistenceWarning,
    }),
    [locale, persistenceWarning, setLocale, t, toggleLocale],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used inside LocaleProvider");
  return value;
}

export function LocaleToggle({ className = "" }: { readonly className?: string }) {
  const { locale, t, toggleLocale } = useLocale();
  const target = locale === "zh-CN" ? "en-US" : "zh-CN";
  return (
    <button
      className={className}
      type="button"
      aria-label={
        target === "en-US"
          ? t("language.switchToEnglish")
          : t("language.switchToChinese")
      }
      onClick={toggleLocale}
    >
      <span lang={target}>{target === "en-US" ? "EN" : "中文"}</span>
    </button>
  );
}
